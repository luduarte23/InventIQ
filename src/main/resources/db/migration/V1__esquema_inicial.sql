-- V1: esquema inicial según ACUERDOS §3

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE suppliers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100)  NOT NULL,
    whatsapp_number  VARCHAR(20)   NOT NULL,
    lead_time_days   INT           NOT NULL CHECK (lead_time_days >= 0),
    min_order_amount DECIMAL(19,2),
    min_order_units  INT,
    active           BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE products (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode       VARCHAR(50)   NOT NULL UNIQUE,
    name          VARCHAR(150)  NOT NULL,
    sale_price    DECIMAL(19,2) NOT NULL,
    unit_cost     DECIMAL(19,2) NOT NULL,
    perishable    BOOLEAN       NOT NULL,
    supplier_id   BIGINT        REFERENCES suppliers (id),
    safety_stock  INT           NOT NULL CHECK (safety_stock >= 0),
    reorder_point INT           NOT NULL DEFAULT 0,
    active        BOOLEAN       NOT NULL DEFAULT TRUE,
    version       BIGINT        NOT NULL DEFAULT 0
);

CREATE TABLE purchase_orders (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id        BIGINT        REFERENCES suppliers (id),
    status             VARCHAR(30)   NOT NULL,
    needs_review       BOOLEAN       NOT NULL DEFAULT FALSE,
    deferred_by_budget BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    approved_at        TIMESTAMP WITH TIME ZONE,
    sent_at            TIMESTAMP WITH TIME ZONE,
    received_at        TIMESTAMP WITH TIME ZONE,
    total_cost         DECIMAL(19,2) NOT NULL
);

CREATE TABLE purchase_order_lines (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          BIGINT        NOT NULL REFERENCES purchase_orders (id),
    product_id        BIGINT        NOT NULL REFERENCES products (id),
    quantity_ordered  INT           NOT NULL CHECK (quantity_ordered > 0),
    quantity_received INT           NOT NULL DEFAULT 0 CHECK (quantity_received >= 0),
    unit_cost         DECIMAL(19,2) NOT NULL,
    added_by_moq      BOOLEAN       NOT NULL DEFAULT FALSE
);

CREATE TABLE batches (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         BIGINT        NOT NULL REFERENCES products (id),
    quantity_received  INT           NOT NULL CHECK (quantity_received >= 0),
    quantity_remaining INT           NOT NULL CHECK (quantity_remaining >= 0),
    expiration_date    DATE,
    received_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    unit_cost          DECIMAL(19,2) NOT NULL,
    discount_percent   DECIMAL(5,2)  NOT NULL DEFAULT 0.00
                       CHECK (discount_percent BETWEEN 0 AND 100),
    purchase_order_id  BIGINT        REFERENCES purchase_orders (id),
    version            BIGINT        NOT NULL DEFAULT 0
);

CREATE TABLE sales (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cashier_id  BIGINT        NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_at   TIMESTAMP WITH TIME ZONE,
    total       DECIMAL(19,2) NOT NULL DEFAULT 0.00
);

CREATE TABLE sale_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id          BIGINT        NOT NULL REFERENCES sales (id),
    product_id       BIGINT        NOT NULL REFERENCES products (id),
    batch_id         BIGINT        NOT NULL REFERENCES batches (id),
    quantity         INT           NOT NULL CHECK (quantity > 0),
    unit_price       DECIMAL(19,2) NOT NULL,
    discount_percent DECIMAL(5,2)  NOT NULL DEFAULT 0.00
                     CHECK (discount_percent BETWEEN 0 AND 100)
);

CREATE TABLE settings (
    id                         BIGINT PRIMARY KEY CHECK (id = 1),
    weekly_budget              DECIMAL(19,2) NOT NULL,
    sales_window_days          INT           NOT NULL DEFAULT 30,
    review_period_days         INT           NOT NULL DEFAULT 7,
    expiry_review_horizon_days INT           NOT NULL DEFAULT 30,
    admin_whatsapp_number      VARCHAR(20)   NOT NULL
);

CREATE TABLE audit_logs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_user_id BIGINT        REFERENCES users (id),
    action        VARCHAR(50)   NOT NULL,
    entity_type   VARCHAR(100)  NOT NULL,
    entity_id     BIGINT        NOT NULL,
    details       VARCHAR(2000)
);

CREATE TABLE alerts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    type                VARCHAR(50)  NOT NULL,
    message             VARCHAR(500) NOT NULL,
    related_entity_type VARCHAR(100),
    related_entity_id   BIGINT,
    resolved            BOOLEAN      NOT NULL DEFAULT FALSE
);

